# -*- coding: utf-8 -*-
"""Builds supabase/seed/ananya_record_set.sql from the authoritative extract.

The first parser written for this file silently dropped two records — R007 and
R024 — because they carry a fourth pipe-delimited field marking the
supersession chain. They were the two most important records in the set. The
count check that caught it runs below on every build, and the build fails
rather than emitting a seed that is quietly two records short.
"""
import re, sys, collections

SRC = '/root/.claude/uploads/738555af-a230-5d22-b6e2-81f18c8bfdc0/fdc2ade6-ananya_record_set.md'
s = open(SRC).read()

# The optional fourth field is what the first attempt missed.
BLOCK = re.compile(
    r'```\n\[R(\d+)\]\s+(\d{4}-\d{2}-\d{2})\s*\|\s*(\w+)\s*\|\s*(\w+)\s*(?:\|\s*([^\n]*?))?\n'
    r'(.*?)\((\w+)\)\s*\|\s*(\w+)\s*\|\s*(\w+)\n(.*?)\n(.*?)\n```', re.S)

recs = []
for m in BLOCK.finditer(s):
    rid, date, dom, sen, note, who, role, src, val, title, content = m.groups()
    recs.append(dict(rid=int(rid), date=date, dom=dom, sen=sen, note=(note or '').strip(),
                     who=who.strip(), role=role, src=src, val=val,
                     title=title.strip(), content=' '.join(content.split())))

declared = sorted({int(x) for x in re.findall(r'\[R(\d+)\]', s)})
got = sorted(r['rid'] for r in recs)
if got != declared:
    print('PARSE FAILED — records in the file that were not parsed:',
          sorted(set(declared) - set(got)))
    sys.exit(1)
print(f'parsed {len(recs)} records, ids R{min(got):03d}–R{max(got):03d}, none dropped')

print('  months:', dict(sorted(collections.Counter(r["date"][:7] for r in recs).items())))
print('  domains:', dict(collections.Counter(r['dom'] for r in recs)))
print('  sensitivity:', dict(collections.Counter(r['sen'] for r in recs)))
print('  roles:', dict(collections.Counter(r['role'] for r in recs)))

# supersession, read from the fourth field rather than assumed
sup = {}
for r in recs:
    m = re.match(r'SUPERSEDES R(\d+)', r['note'], re.I)
    if m: sup[r['rid']] = int(m.group(1))
print('  supersession chains:', {f'R{k:03d}': f'R{v:03d}' for k, v in sup.items()})

gap = [r for r in recs if '2026-05-17' <= r['date'] <= '2026-07-27']
print(f'  gap window 17 May–27 Jul: {len(gap)} records, '
      f'{sum(1 for r in gap if r["src"] == "self_reported")} self-reported')

# ------------------------------------------------------------------- emit
def q(v):
    if v is None: return 'null'
    if isinstance(v, list):
        return "array[" + ",".join("'" + x.replace("'","''") + "'" for x in v) + "]::text[]" if v else 'null'
    return "'" + str(v).replace("'", "''") + "'"

S = 'aaaaaaaa-0000-0000-0000-00000000000a'
U = {'patient':'e0000000-0000-0000-0000-000000000001',
     'trusted_person':'e0000000-0000-0000-0000-000000000002',
     'psychologist':'e0000000-0000-0000-0000-000000000003',
     'psychiatrist':'e0000000-0000-0000-0000-000000000004',
     'ot':'e0000000-0000-0000-0000-000000000005',
     'therapist':'e0000000-0000-0000-0000-000000000006',
     'gp':'e0000000-0000-0000-0000-000000000007',
     'coordinator':'e0000000-0000-0000-0000-000000000008',
     'employer':'e0000000-0000-0000-0000-000000000009',
     'university':'e0000000-0000-0000-0000-00000000000a',
     'admin':'e0000000-0000-0000-0000-00000000000b',
     'system': None}
iid = lambda n: 'f0000000-0000-0000-0000-%012d' % n
EV = {'professional_validated':0.9,'subject_confirmed':0.75,'unvalidated':0.5,'outdated':0.4}

O=[]; w=O.append
w("-- Ananya Rao — longitudinal record extract, seeded verbatim.")
w("--")
w("-- GENERATED by scripts/build_record_set.py from the authoritative extract.")
w("-- Edit the extract and regenerate; do not edit this file.")
w("--")
w("-- 41 records, September 2025 to August 2026. All fictional.")
