 ('psychiatrist',['clinical','functional'],'care','2025-11-10'),
 ('ot',['functional','support'],'support_planning','2025-10-05'),
 ('therapist',['functional','support'],'support_planning','2026-02-10'),
 ('trusted_person',['personal','support'],'personal_understanding','2025-09-01'),
