for sid,name,roles in CASELOAD:
    w("insert into stakeholder_relationships (subject_id, user_id, role, purpose, valid_from) values")
    parts=["  (%s, %s, 'patient', 'personal_understanding', '2025-09-01T00:00:00Z')" % (q(sid), q(U['patient']))]
    for role in roles:
        pur = 'care' if role in ('psychologist','gp','psychiatrist') else \
              ('coordination' if role=='coordinator' else 'support_planning')
        parts.append("  (%s, %s, %s, %s, '2025-09-01T00:00:00Z')" % (q(sid), q(U[role]), q(role), q(pur)))
    w(",\n".join(parts) + ";")
    for i in range(6):
        d='2026-%02d-%02d' % (2+i, 6+i)
        w("select orca_write_record(%s, %s::record_domain," % (q(sid), q(DOMS[i])))
        w("  %s, 'professional_reported'::source_type, 'psychologist'::stakeholder_role," %
          q('Caseload placeholder %d for %s. Not developed; present so a caseload exists.' % (i+1, name)))
        w("  %s::timestamptz, %s, %s," % (q(d+'T09:00:00Z'), q('Caseload note %d'%(i+1)), q(U['psychologist'])))
        w("  'moderate'::sensitivity_level, 'professional_validated'::validation_status, 0.5, null, null, null);")
    w("")
w("commit;")
