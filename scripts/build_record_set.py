w("-- The build refuses to emit unless every [Rnnn] in the source is parsed. The")
w("-- first parser written for it dropped R007 and R024 — the two carrying the")
w("-- supersession chain, because they have a fourth pipe-delimited field — and")
w("-- would have produced a seed that looked complete and was missing exactly")
w("-- the records the dataset exists to demonstrate.")
w("--")
w("-- Relationship dates bind: the roster below is what makes an employer unable")
w("-- to read anything before March 2026, whatever domain it sits in.")
w("")
w("begin;")
w("")
w("delete from context_briefs where subject_id = %s;" % q(S))
w("delete from agents_run where run_id in (select run_id from runs where subject_id = %s);" % q(S))
w("delete from support_outcomes; delete from support_strategies;")
w("delete from files; delete from consents;")
w("delete from record_items where subject_id in (select subject_id from subjects")
w("  where display_name in ('Ananya Rao','Rohan Mehta','Farida Qureshi','Dev Sharma','Neha Iyer'));")
w("delete from stakeholder_relationships where subject_id in (select subject_id from subjects")
w("  where display_name in ('Ananya Rao','Rohan Mehta','Farida Qureshi','Dev Sharma','Neha Iyer'));")
w("delete from subjects where display_name in")
w("  ('Ananya Rao','Rohan Mehta','Farida Qureshi','Dev Sharma','Neha Iyer');")
w("delete from users where email like '%@orca.example';")
w("")

SUBJ=[(S,'Ananya Rao','1997-03-14'),
      ('aaaaaaaa-0000-0000-0000-00000000000b','Rohan Mehta','1994-08-02'),
      ('aaaaaaaa-0000-0000-0000-00000000000c','Farida Qureshi','1999-01-27'),
      ('aaaaaaaa-0000-0000-0000-00000000000d','Dev Sharma','1991-11-09'),
      ('aaaaaaaa-0000-0000-0000-00000000000e','Neha Iyer','2001-06-21')]
w("insert into subjects (subject_id, display_name, date_of_birth) values")
w(",\n".join("  (%s, %s, %s)" % (q(a),q(b),q(c)) for a,b,c in SUBJ) + ";")
w("")
# Emails written out rather than derived from the surname. Three of the eleven
# are Raos — Ananya, her sister Divya, and her GP Vikram — so a derived address
