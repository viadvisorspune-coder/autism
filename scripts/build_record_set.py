for r in recs:
    w("select orca_write_record(")
    w("  %s, %s::record_domain, %s," % (q(S), q(r['dom']), q(r['content'])))
    w("  %s::source_type, %s::stakeholder_role," % (q(r['src']), q(r['role'])))
    w("  %s::timestamptz, %s, %s," % (q(r['date']+'T09:00:00Z'), q(r['title']), q(U.get(r['role']))))
    w("  %s::sensitivity_level, %s::validation_status, %s, null, null, %s);"
      % (q(r['sen']), q(r['val']), EV.get(r['val'], 0.5), q(iid(r['rid']))))
w("")
w("-- The correction, through orca_supersede so both links and both is_current")
